// Greek home cooking, one serving each. Every ingredient name matches an
// entry in ingredientCatalog.ts exactly, so calories add up.
type Item = [name: string, amount: number, unit?: Unit]

function recipe(
  id: number,
  title: string,
  category: Category,
  mealTypes: SlotKey[],
  items: Item[],
  instructions: string,
): Recipe {
  // Written in grams; countable things become pieces ("2 αυγά").
  const ingredients: Ingredient[] = items.map(([name, amount, unit = 'g']) =>
    toNaturalUnit({ name, amount, unit }, DEFAULT_INGREDIENT_CATALOG),
  )
  const meta = META[id]
  return {
    id: `gr-${id}`,
    title,
    category,
    mealTypes,
    servings: 1,
    ...(meta ? { minutes: meta[0], difficulty: DIFF[meta[1]], keepsDays: meta[2] } : {}),
    ingredients,
    instructions,
  }
}

